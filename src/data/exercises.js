export function getExerciseById(id) {
  return exercises.find((e) => e.id === id) ?? null;
}

/** All exercises that target the given muscle (case-insensitive match on musclesUsed) */
export function getExercisesByMuscle(muscleName) {
  if (!muscleName || !muscleName.trim()) return [];
  const lower = muscleName.trim().toLowerCase();
  return exercises.filter(
    (e) =>
      (e.musclesUsed || []).some((m) => m.trim().toLowerCase() === lower)
  );
}

/** Primary = first 2 muscles, Secondary = rest (for display when not explicitly set) */
export function getPrimaryMuscles(ex) {
  const muscles = ex.primaryMuscles ?? ex.musclesUsed ?? [];
  if (ex.primaryMuscles) return ex.primaryMuscles;
  return muscles.slice(0, 2).filter(Boolean);
}

export function getSecondaryMuscles(ex) {
  const muscles = ex.secondaryMuscles ?? ex.musclesUsed ?? [];
  if (ex.secondaryMuscles) return ex.secondaryMuscles;
  return (ex.musclesUsed ?? []).slice(2).filter(Boolean);
}

